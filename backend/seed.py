            prepared = [dict(q, id=f'{slug}-{i+1}') for i, q in enumerate(questions)]
            db.execute('INSERT OR IGNORE INTO sets VALUES (?,?,?,?,?,?,?,?,?,?)',
                       (f'example-{slug}', 'examhub-originals', title, description, topic, 'public', 1,
                        json.dumps(prepared, ensure_ascii=False), now(), None))
